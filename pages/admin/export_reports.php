/**
 * Converts a Firestore/PHP date value into a unix timestamp (or null).
 */
function export_timestamp($value): ?int
{
    if ($value === null) return null;
    if ($value instanceof \Google\Cloud\Core\Timestamp) return $value->get()->getTimestamp();
    if ($value instanceof \DateTimeInterface) return $value->getTimestamp();
    if (is_numeric($value)) {
        $ts = (int) $value;
        return $ts > 9999999999 ? (int) ($ts / 1000) : $ts;
    }
    if (is_string($value)) {
        $ts = strtotime($value);
        return $ts !== false ? $ts : null;
    }
    return null;
}

function e($v): string
{
    return htmlspecialchars((string) $v, ENT_QUOTES, 'UTF-8');
}

